// Bundles the agent app toolchain into dist/toolchain.js: the SDK, the release entry and the transpiler as ESM source
// strings for Dynamic Workers, the agent's docs, and one hash over all of it (ADR 0021).
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'

const root = new URL('..', import.meta.url).pathname

/** Leaves the app's own module to the release's module map: the entry imports `./app.js` as it will be there. */
const appModule: Bun.BunPlugin = {
  name: 'app-module',
  setup(build) {
    build.onResolve({ filter: /^\.\/app\.js$/u }, () => ({ path: './app.js', external: true }))
  },
}

async function bundle(entry: string, external: readonly string[]): Promise<string> {
  const result = await Bun.build({
    entrypoints: [`${root}src/${entry}`],
    format: 'esm',
    target: 'browser',
    minify: entry === 'transpile.ts',
    external: [...external],
    plugins: [appModule],
  })
  if (!result.success) throw new AggregateError(result.logs, `build of ${entry} failed`)
  const [output] = result.outputs
  if (output === undefined) throw new Error(`build of ${entry} produced nothing`)
  return output.text()
}

const sdk = await bundle('sdk.ts', [])
const release = await bundle('release.ts', ['cloudflare:workers'])
const transpiler = await bundle('transpile.ts', ['cloudflare:workers'])
const docs: Record<string, string> = {}
for (const file of (await readdir(`${root}docs`)).toSorted())
  if (file.endsWith('.md')) docs[file.replace(/\.md$/u, '')] = await readFile(`${root}docs/${file}`, 'utf8')
const hash = createHash('sha256').update(JSON.stringify({ sdk, release, transpiler })).digest('hex').slice(0, 16)

const module = [
  '// Generated by packages/app/scripts/build.ts. Do not edit.',
  `export const TOOLCHAIN_HASH = ${JSON.stringify(hash)}`,
  `export const SDK = ${JSON.stringify(sdk)}`,
  `export const RELEASE = ${JSON.stringify(release)}`,
  `export const TRANSPILER = ${JSON.stringify(transpiler)}`,
  `export const DOCS = ${JSON.stringify(docs)}`,
  '',
].join('\n')
await mkdir(`${root}dist`, { recursive: true })
await writeFile(`${root}dist/toolchain.js`, module)
console.info(
  `@goblin/app toolchain ${hash}: sdk ${sdk.length} B, release ${release.length} B, transpiler ${transpiler.length} B`,
)
